import 'dart:convert';
import 'package:cryptography/cryptography.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';

import 'package:mira_finance_tracker/classes/account/User.dart';

/// Class to manage key encryption, decryption,
/// save and creation, to keep them inside the 
/// program in a secure way
class KeyManager{
  /* define private attributes 
  to be used inside the flutter secure storage 
  to store cryptography keys */
  static final String _USERKEYPREFIX = "cryptouser_";
  static final String _APPLICATIONDATABASE = "cryptosystem_database";

  /* configure private attributes to configure
  flutter secure storage environment and 
  cryptography settings */
  static final FlutterSecureStorage _secureStorage = const FlutterSecureStorage(
    aOptions: AndroidOptions(resetOnError: true),
    iOptions: IOSOptions(accessibility: KeychainAccessibility.first_unlock),
  );
  static final AesGcm _aesAlgorithm = AesGcm.with256bits();

  /* define attribute to store information for the single instance 
  about the cryptography key given */
  SecretKey? _activeKey;
  String? _username;

  /// Constructor method which tries directly to
  /// find the key and set it as an attribute
  /// in order to make it easier to encrypt and decrypt data
  /// * [user] eventual user associated to the key
  /// * [search] flag to indicated if the key has to be searched immediately
  KeyManager({User? user, bool search = true}){
    _username = user?.username; // save the username

    if(search) recoverKey(); // recover the key if requested
  }

  /* *** GETTER METHODS *** */
  bool get isAuthenticated => _username != null;
  bool get isPasswordSet => _activeKey != null;
  Future<String?> get stringKey async {
    if(_activeKey == null){
      return null;
    }

    return base64Encode(await _activeKey!.extractBytes());
  }

  /// Function to clear the session 
  /// erasing username and active user key
  void clearSession(){
    _activeKey = null;
    _username = null;
  }

  /// Function to generate a random key
  /// for local application environment
  Future<void> generateRandomKey() async{
    if(isAuthenticated){
      throw Exception("Can't generate a random key for the user because it needs a master password to cypher it");
    }
    if(_activeKey != null){
      throw Exception("Key already set, can't find other");
    }

    /* generate the random key and save it
    inside the flutter secure storage */
    _activeKey = await _aesAlgorithm.newSecretKey();
    await _secureStorage.write(key: _APPLICATIONDATABASE, value: await stringKey);
  }

  /* function to generate
  random salt to create the password */
  Future<List<int>> _generateSalt([int length = 16]) async {
    final algorithm = AesGcm.with256bits();
    // newSecretKey() genera 32 byte casuali protetti
    final newKey = await algorithm.newSecretKey();
    final bytes = await newKey.extractBytes();
    
    // Prendi i primi 'length' byte (es. 16 byte)
    return bytes.sublist(0, length);
  }
  
  /// Function to generate a key 
  /// from the password given to unlock
  /// a random key which will be automatically generated by the user
  /// * [password] password given from the user
  /// * [givenSalt] salt given from the user
  Future<void> generateKeyFromPassword(String password, List<int>? givenSalt) async{
    /* first understand if the user has
    loggerd, otherwise it's not possible to use this function.
    Then see if the key has already been set */
    if(!isAuthenticated){
      throw Exception("The user must be authenticated to use this function");
    }
    if(_activeKey != null){
      throw Exception("Cannot generate new key while another one has already been set");
    }

    /* generate the password combined with the salt */
    final pbkdf2 = Pbkdf2(
      macAlgorithm: Hmac.sha256(),
      iterations: 100000,
      bits: 256,
    );
    List<int> salt = givenSalt ?? await _generateSalt();
    SecretKey lockerKey = await pbkdf2.deriveKey(
      secretKey: SecretKey(utf8.encode(password)),
      nonce: salt,
    );

    /* generate the random secret key
    to protect a random key generated by the system, 
    which will effectively protect the user's data */
    SecretKey userKey = await _aesAlgorithm.newSecretKey();

    /* save the secret key as an attribute
    and inside the flutter secure storage */
    _saveUserKey(password, lockerKey, userKey, salt);
  }

  /* common method to save user key as an attribute and 
  inside flutter secure storage */
  Future<void> _saveUserKey(String password, SecretKey lockerKey, SecretKey userKey, List<int> salt) async {
    _activeKey = userKey;
      /* first save data as a json to encode
      inside a string value */
      String data = jsonEncode({
        'lockerKey': base64Encode(await lockerKey.extractBytes()),
        'userKey': base64Encode(await userKey.extractBytes()),
        'salt': base64Encode(salt),
        'password': password
      });

    await _secureStorage.write(key: "$_USERKEYPREFIX$_username", value: data);
  }

  /* function to understand if the key is saved, 
  so as to avoid to generate it again */
  Future<bool> _checkKeyPresence() async{
    final storageKey = isAuthenticated ? "$_USERKEYPREFIX$_username" : _APPLICATIONDATABASE;
    return await _secureStorage.containsKey(key: storageKey);
  }

  /// Function to recover a key from the secure storage
  /// and convert it in the right way to be used
  Future<void> recoverKey() async{
    if (_activeKey != null) {
      return;
    }

    /* try to recover the data with the given keys */
    final storageKey = isAuthenticated ? "$_USERKEYPREFIX$_username" : _APPLICATIONDATABASE;
    final storedValue = await _secureStorage.read(key: storageKey);

    /* if no stored value has been found, 
    generate a random key if it's for the application */
    if ((storedValue == null || storedValue.isEmpty) && !isAuthenticated) {
      await generateRandomKey();
    }
    /* for the user try to get the user key
    otherwise throw an Exception */
    if (isAuthenticated) {
      final decodedData = jsonDecode(storedValue!);
      if (decodedData is! Map<String, dynamic>) {
        throw Exception("Stored key data is not valid");
      }

      final userKeyBase64 = decodedData['userKey'] as String?;
      if (userKeyBase64 == null || userKeyBase64.isEmpty) {
        throw Exception("Missing userKey in stored data");
      }

      _activeKey = SecretKey(base64Decode(userKeyBase64));
    } else {
      _activeKey = SecretKey(base64Decode(storedValue!));
    }
  }

  /// Function to encrypt data starting from the
  /// plain text to encrypt
  /// * [plainText] data to encrypt
  Future<List<int>> encryptData(List<int> plainText) async {
    return _encryptDataWithPassword(plainText, _activeKey);
  }

  Future<List<int>> _encryptDataWithPassword(List<int> plainText, SecretKey? secretKey) async{
    if (secretKey == null) {
      throw Exception("No key provided for database encryption");
    }

    final secretBox = await _aesAlgorithm.encrypt(
      plainText,
      secretKey: secretKey,
    );

    return secretBox.concatenation();
  }

  /// Function used to decrypt data starting from 
  /// the encrypted data and the saved in the object
  /// * [encryptedData] data to decrypt
  Future<List<int>> decryptData(List<int> encryptedData) async {
    if (_activeKey == null) {
      throw Exception("Nessuna chiave di cifratura attiva. Effettuare il login.");
    }

    final secretBox = SecretBox.fromConcatenation(
      encryptedData,
      nonceLength: 12,
      macLength: 16,
    );

    return await _aesAlgorithm.decrypt(
      secretBox,
      secretKey: _activeKey!,
    );
  }

  /// Function to export the data of the crypto key
  /// with salt and all the elements to share this information
  /// in public spaces without compromising the confidentiality
  Future<Map<String, dynamic>> exportKeyData() async{
    /* first check if the user is authenticated, 
    because this operation can be done only for keys
    belonging to accounts */
    if(!isAuthenticated){
      throw Exception("Exporting key data operation must be done only with a local account");
    }

    /* get the various parameters from the secure storage */
    final storedValue = await _secureStorage.read(key: "$_USERKEYPREFIX$_username");
    if(storedValue == null){
      throw Exception("No result found inside the secure storage of cryptography keys");
    }

    final decodedData = jsonDecode(storedValue);
    if (decodedData is! Map<String, dynamic>) {
      throw Exception("Stored key data is not valid");
    }

    final userKey = decodedData['userKey'];
    final salt = decodedData['salt'];
    final lockerKey = SecretKey(base64Decode(decodedData['lockerKey']));

    /* encrypt the user key and return
    the data as a json format */
    final encryptedUserKey = base64Encode(await _encryptDataWithPassword(userKey, lockerKey));

    return {
      'username': _username,
      'salt': salt,
      'userKey': encryptedUserKey
    };
  }

  /// Function to generate cryptography key from the data
  /// imported and the password given 
  /// and return if the decryption has been done successfully
  /// * [password] passkey given by the user to decrypt
  /// * [keyData] data of the user to decrypt
  Future<bool> importKeyData(String password, Map<String, dynamic> keyData) async {
    /* get the data from the json map
    and process them */
    List<int> salt = base64Decode(keyData['salt']);
    await generateKeyFromPassword(password, salt); // get the locker key

    /* try to decrypt the user key, otherwise
    return a false flag */
    try{
      SecretKey userKey = SecretKey(await decryptData(base64Decode(keyData['userKey'])));
      SecretKey lockerKey = _activeKey!; // save current locker key
      _saveUserKey(password, lockerKey, userKey, salt);
      return true;
    }on SecretBoxAuthenticationError{
      return false;
    }
  }

  /// Function to remove the secret key 
  /// and other public information
  /// of the selected user
  void removeKey(){
    if(!isAuthenticated){
      throw Exception("To remove the key of a user it must be authenticated");
    }

    _secureStorage.delete(key: '$_USERKEYPREFIX$_username'); // delete the key
  }

  /// Method to change the passkey given by the user
  /// in case it gets lost or to improve security
  /// * [password] new passkey from the user to cypher the database key
  Future<void> changePassword(String password) async {
    if(!isAuthenticated){
      throw Exception("Cannot change the passkey for crypto when user is not logged");
    }
    if(!isPasswordSet){
      throw Exception("Cannot change the passkey for crypto while active key is still null");
    }

    /* generate the salt and 
    create the key to be saved */
    List<int> salt = await _generateSalt();
    final pbkdf2 = Pbkdf2(
      macAlgorithm: Hmac.sha256(),
      iterations: 100000,
      bits: 256,
    );
    SecretKey lockerKey = await pbkdf2.deriveKey(
      secretKey: SecretKey(utf8.encode(password)),
      nonce: salt,
    );

    _saveUserKey(password, lockerKey, _activeKey!, salt);
  }
}