import 'package:meta/meta.dart';

import 'package:mira_finance_tracker/classes/time_management/PeriodicAccountDuration.dart';
import 'package:mira_finance_tracker/classes/transaction/BankTransaction.dart';

/// Class to manage general periodic billings
/// inside a bank account.
/// This class will be specified in domiciliation and cashback
/// applied to a bank account
abstract class PeriodicAccountBillings{
  /* attributes definition */
  int _id;
  String _name;
  String? _description;
  double _amount;
  PeriodicAccountDuration _cadence;

  /// Constructor method of the periodic account billings 
  /// inside a bank account, with all the parameters needed
  /// * [_name] name of the billing (unique)
  /// * [_amount] amount of money of the billing
  /// * [_cadence] temporal cadence of the billing
  /// * [_description] optional description of the billing
  /// * [_id] ID of the building (if negative it hasn't been set yet)
  PeriodicAccountBillings(this._name, this._amount, this._cadence, {this._description, this._id = -1});

  /* *** GETTER METHODS *** */
  int get id => _id;
  String get name => _name;
  String? get description => _description;
  double get amount => _amount;
  PeriodicAccountDuration get cadence => _cadence.clone();
  @protected
  PeriodicAccountDuration get originalCadence => _cadence;

  /* *** SETTER METHODS *** */
  set description(String? description) => _description = description;
  set amount(double amount) {
    if(amount<0){
      throw Exception("Amount can't be less than 0 for a periodic account billing");
    }
    _amount = amount;
  }
  set cadence(PeriodicAccountDuration cadence) => _cadence = cadence;

  /// Operator of equals which compares the two periodic account billings
  /// using the name, which unique for every account billing
  /// * [other] object to be compared
  @override
  bool operator ==(Object other){
    return other is PeriodicAccountBillings && other.runtimeType == runtimeType && 
      other._name == _name;
  }

  /// Getter of the hashcode
  @override
  int get hashCode => _name.hashCode;

  /// Function to convert a periodic account billing into
  /// a map used for database manipulation
  Map<String, dynamic> toMap(){
    /* get the map of the billing */
    Map<String, dynamic> billingMap = {
      if(_id >= 0) 'id': _id,
      'name': _name,
      'description': _description,
      'amount': _amount,
    };

    /* add to it the map of the 
    cadence generated by the object
    and return it out */
    return {...billingMap, ..._cadence.toMap()};
  }

  /// Function to check and execute billings and return
  /// a list of bank transactions for the account selected
  List<BankTransaction>? checkAndExecute();

  /// Method to get a deep clone of the instance
  PeriodicAccountBillings clone();
}