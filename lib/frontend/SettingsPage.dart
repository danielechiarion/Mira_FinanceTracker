import 'package:flutter/material.dart';

import 'package:mira_finance_tracker/classes/account/User.dart';
import 'package:mira_finance_tracker/backend/operation/account/GoogleAccountDisconnection.dart';
import 'package:mira_finance_tracker/backend/service/security/LocalAuthSupport.dart';
import 'package:mira_finance_tracker/backend/service/KeyManager.dart';
import 'package:mira_finance_tracker/frontend/account/AccountSettingsPage.dart';
import 'package:mira_finance_tracker/frontend/navbar/ResponsiveScaffold.dart';
import 'package:mira_finance_tracker/frontend/navbar/AppRoutes.dart';
import 'package:mira_finance_tracker/backend/service/preference/UserPreferences.dart';
import 'package:mira_finance_tracker/backend/service/session/CurrentSession.dart';
import 'package:mira_finance_tracker/frontend/account/GoogleConnectionPage.dart';

/// Main entry point for the Settings feature.
/// Displays the account shortcut and the application-wide preferences
/// (background activity, notifications and the changing period window).
/// Cloud settings are intentionally omitted for now, since they are
/// still to be configured on the backend side.
class SettingsPage extends StatefulWidget {
  const SettingsPage({super.key});

  @override
  State<SettingsPage> createState() => _SettingsPageState();
}

class _SettingsPageState extends State<SettingsPage> {
  /// Local copy of the current user, kept in the state so it can be
  /// refreshed immediately after coming back from the account subpage.
  late User _currentUser;
  late UserPreferences _preferences;
  bool _isLoading = true;

  /// Whether the periodic background activity is enabled
  /// (monthly reviews, automatic income/outgoing calculations, etc.).
  late bool _backgroundActivityEnabled;

  /// Whether the application is allowed to show notifications
  /// generated by the background activity.
  late bool _notificationsEnabled;

  /// Number of years the user can go backwards to edit past movements
  /// and the window used for incremental backups.
  late int _changingPeriodYears;
  bool _googleAccountAssociated = false;
  bool _isDisconnectingGoogle = false;

  @override
  void initState() {
    super.initState();
    _loadData();
  }

  /// Function to load all data from session
  /// and shared preferences and make it available
  /// for the settings page
  Future<void> _loadData() async {
    /* initialize data from the current session */
    CurrentSession session = (await CurrentSession.getFromMemory())!;
    setState(() {
      _currentUser = session.user;
      _googleAccountAssociated = session.user.email.isNotEmpty;
    });

    /* initialize user preferences 
    and upload the data correctly */
    _preferences = UserPreferences(_currentUser);
    await _preferences.init();

    setState(() {
      /* then read the values from 
      the user preferences */
      _backgroundActivityEnabled = _preferences
          .getPreference('enableBackground')
          .currentValue;
      _notificationsEnabled = _preferences
          .getPreference('enableNotifications')
          .currentValue;
      _changingPeriodYears = _preferences
          .getPreference('backupTime')
          .currentValue;
      _isLoading = false;
    });
  }

  /// Opens the account subpage and refreshes the displayed user data
  /// if something changed (name, surname, username, ...).
  Future<void> _openAccountSettings() async {
    final User? updatedUser = await Navigator.push(
      context,
      MaterialPageRoute(
        builder: (context) => AccountSettingsPage(currentUser: _currentUser),
      ),
    );

    // Refresh the summary shown on this page as soon as we come back
    if (updatedUser != null) {
      setState(() {
        _currentUser = updatedUser;
      });
    }
  }

  /// Opens the optional Google connection flow and refreshes the account banner.
  Future<void> _connectGoogleAccount() async {
    await Navigator.push<bool>(
      context,
      MaterialPageRoute(
        builder: (context) =>
            GoogleConnectionPage(user: _currentUser, returnToSettings: true),
      ),
    );

    if (!mounted) return;
    setState(() {
      _googleAccountAssociated = _currentUser.email.isNotEmpty;
    });
  }

  /// Shows the saved encryption passkey after device authentication succeeds.
  Future<void> _showEncryptionPasskey() async {
    try {
      final authenticated = await LocalAuthSupport.authenticate(
        'Sblocca per visualizzare la passkey di crittografia',
      );
      if (!authenticated || !mounted) return;

      final keyManager = KeyManager(user: _currentUser);
      String? encryptionPasskey;
      try {
        await keyManager.init();
        encryptionPasskey = await keyManager.encryptionPasskey;
      } finally {
        keyManager.clearSession();
      }
      if (!mounted) return;
      final passkeyToDisplay = encryptionPasskey;
      if (passkeyToDisplay == null || passkeyToDisplay.isEmpty) {
        _showMessage('La passkey di crittografia non è disponibile.');
        return;
      }

      await showDialog<void>(
        context: context,
        builder: (dialogContext) => AlertDialog(
          title: const Text('Passkey di crittografia'),
          content: SelectableText(
            passkeyToDisplay,
            style: const TextStyle(fontFamily: 'monospace'),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(dialogContext),
              child: const Text('Chiudi'),
            ),
          ],
        ),
      );
    } catch (error) {
      if (mounted) {
        _showMessage('Impossibile visualizzare la chiave: $error');
      }
    }
  }

  /// Confirms and disconnects Google, cleaning cloud data when permitted.
  Future<void> _disconnectGoogleAccount() async {
    final email = _currentUser.email;
    if (email.isEmpty) return;

    final confirmed = await showDialog<bool>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: const Text('Disconnettere Google?'),
        content: const Text(
          'I dati presenti nello spazio cloud verranno eliminati se non ci '
          'sono altri dispositivi registrati. Questa operazione non è reversibile.',
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, false),
            child: const Text('Annulla'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(dialogContext, true),
            child: const Text('Disconnetti'),
          ),
        ],
      ),
    );
    if (confirmed != true || !mounted) return;

    setState(() => _isDisconnectingGoogle = true);
    try {
      final result = await GoogleAccountDisconnection(_currentUser).execute();

      if (!mounted) return;
      setState(() {
        _googleAccountAssociated = false;
        _isDisconnectingGoogle = false;
      });
      _showMessage(result.message);
    } catch (error) {
      if (mounted) {
        setState(() {
          _googleAccountAssociated = _currentUser.email.isNotEmpty;
          _isDisconnectingGoogle = false;
        });
        _showMessage('Disconnessione Google non riuscita: $error');
      }
    }
  }

  void _showMessage(String message) {
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(SnackBar(content: Text(message)));
  }

  @override
  Widget build(BuildContext context) {
    /* if the content is still loading
    put a circular progress indicator */
    if (_isLoading) {
      return ResponsiveScaffold(
        currentRoute: AppRoutes.settings,
        title: 'Impostazioni',
        body: Center(child: CircularProgressIndicator()),
      );
    }

    return ResponsiveScaffold(
      currentRoute: AppRoutes.settings,
      title: 'Impostazioni',
      body: SafeArea(
        child: ListView(
          padding: const EdgeInsets.all(20.0),
          children: [
            _buildSectionTitle('Account'),
            const SizedBox(height: 8),
            Card(
              elevation: 1,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(12),
              ),
              child: ListTile(
                contentPadding: const EdgeInsets.symmetric(
                  horizontal: 16,
                  vertical: 8,
                ),
                leading: const CircleAvatar(
                  backgroundColor: Colors.teal,
                  child: Icon(Icons.person, color: Colors.white),
                ),
                title: const Text(
                  'Account e profilo',
                  style: TextStyle(fontWeight: FontWeight.bold),
                ),
                subtitle: Text(_currentUser.username),
                trailing: const Icon(
                  Icons.arrow_forward_ios,
                  size: 16,
                  color: Colors.teal,
                ),
                onTap: _openAccountSettings,
              ),
            ),
            if (_googleAccountAssociated) ...[
              const SizedBox(height: 8),
              Card(
                elevation: 1,
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(12),
                ),
                child: ListTile(
                  contentPadding: const EdgeInsets.symmetric(
                    horizontal: 16,
                    vertical: 8,
                  ),
                  leading: const CircleAvatar(
                    backgroundColor: Colors.white,
                    child: Icon(
                      Icons.g_mobiledata,
                      color: Colors.teal,
                      size: 32,
                    ),
                  ),
                  title: const Text(
                    'Account Google collegato',
                    style: TextStyle(fontWeight: FontWeight.bold),
                  ),
                  subtitle: Text(_currentUser.email),
                  trailing: _isDisconnectingGoogle
                      ? const SizedBox(
                          width: 22,
                          height: 22,
                          child: CircularProgressIndicator(
                            strokeWidth: 2,
                            color: Colors.teal,
                          ),
                        )
                      : IconButton(
                          tooltip: 'Disconnetti Google e pulisci il cloud',
                          onPressed: _disconnectGoogleAccount,
                          icon: const Icon(
                            Icons.link_off,
                            color: Colors.redAccent,
                          ),
                        ),
                ),
              ),
            ] else ...[
              const SizedBox(height: 8),
              Card(
                elevation: 1,
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(12),
                ),
                child: ListTile(
                  contentPadding: const EdgeInsets.symmetric(
                    horizontal: 16,
                    vertical: 8,
                  ),
                  leading: const CircleAvatar(
                    backgroundColor: Colors.teal,
                    child: Icon(Icons.cloud_outlined, color: Colors.white),
                  ),
                  title: const Text(
                    'Collega un account Google',
                    style: TextStyle(fontWeight: FontWeight.bold),
                  ),
                  subtitle: const Text(
                    'Connetti Google Drive per usare backup e sincronizzazione cloud.',
                  ),
                  trailing: const Icon(
                    Icons.arrow_forward_ios,
                    size: 16,
                    color: Colors.teal,
                  ),
                  onTap: _connectGoogleAccount,
                ),
              ),
            ],
            const SizedBox(height: 28),

            _buildSectionTitle('Applicazione'),
            const SizedBox(height: 8),
            Card(
              elevation: 1,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(12),
              ),
              child: Column(
                children: [
                  // --- BACKGROUND ACTIVITY TOGGLE ---
                  SwitchListTile(
                    secondary: const Icon(Icons.sync, color: Colors.teal),
                    activeThumbColor: Colors.teal,
                    title: const Text(
                      'Attività in background',
                      style: TextStyle(fontWeight: FontWeight.bold),
                    ),
                    subtitle: const Text(
                      'Controlla periodicamente i conti per calcolare in automatico entrate, '
                      'uscite e revisioni mensili. Se disattivata, i pagamenti e le entrate '
                      'periodiche dovranno essere inserite manualmente.',
                    ),
                    value: _backgroundActivityEnabled,
                    onChanged: (bool value) async {
                      setState(() {
                        _backgroundActivityEnabled = value;
                        // Notifications depend on the background activity: if it gets
                        // disabled there is nothing left that could trigger them
                        if (!value) _notificationsEnabled = false;
                      });

                      await _preferences.updatePreferenceValue(
                        'enableBackground',
                        value,
                      );
                    },
                  ),
                  const Divider(height: 1),

                  // --- NOTIFICATIONS TOGGLE ---
                  SwitchListTile(
                    secondary: const Icon(
                      Icons.notifications_none,
                      color: Colors.teal,
                    ),
                    activeThumbColor: Colors.teal,
                    title: const Text(
                      'Notifiche',
                      style: TextStyle(fontWeight: FontWeight.bold),
                    ),
                    subtitle: Text(
                      _backgroundActivityEnabled
                          ? 'Ricevi notifiche sulle revisioni mensili e sui pagamenti periodici in scadenza.'
                          : 'Attiva l\'attività in background per poter ricevere notifiche.',
                    ),
                    value: _notificationsEnabled,
                    // Disabled (greyed out) whenever the background activity is off,
                    // since in that case no notification could ever be produced
                    onChanged: _backgroundActivityEnabled
                        ? (bool value) async {
                            setState(() {
                              _notificationsEnabled = value;
                            });

                            await _preferences.updatePreferenceValue(
                              'enableNotifications',
                              value,
                            );
                          }
                        : null,
                  ),
                  const Divider(height: 1),

                  // --- CHANGING PERIOD WINDOW ---
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 12, 16, 4),
                    child: Row(
                      children: [
                        const Icon(Icons.history, color: Colors.teal),
                        const SizedBox(width: 16),
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              const Text(
                                'Finestra di modifica',
                                style: TextStyle(fontWeight: FontWeight.bold),
                              ),
                              const SizedBox(height: 4),
                              Text(
                                'Anni per cui è possibile modificare i movimenti passati e '
                                'generare i backup incrementali.',
                                style: TextStyle(
                                  fontSize: 13,
                                  color: Colors.grey.shade700,
                                ),
                              ),
                            ],
                          ),
                        ),
                      ],
                    ),
                  ),
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 0, 16, 8),
                    child: Row(
                      children: [
                        Expanded(
                          child: Slider(
                            value: _changingPeriodYears.toDouble(),
                            min: 1,
                            max: 10,
                            divisions: 9,
                            activeColor: Colors.teal,
                            label: '$_changingPeriodYears anni',
                            onChanged: (double value) async {
                              setState(() {
                                _changingPeriodYears = value.round();
                              });

                              await _preferences.updatePreferenceValue(
                                'backupTime',
                                value.round(),
                              );
                            },
                          ),
                        ),
                        SizedBox(
                          width: 56,
                          child: Text(
                            '$_changingPeriodYears anni',
                            textAlign: TextAlign.center,
                            style: const TextStyle(
                              fontWeight: FontWeight.bold,
                              color: Colors.teal,
                            ),
                          ),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 28),
            _buildSectionTitle('Sicurezza'),
            const SizedBox(height: 8),
            Card(
              elevation: 1,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(12),
              ),
              child: ListTile(
                contentPadding: const EdgeInsets.symmetric(
                  horizontal: 16,
                  vertical: 8,
                ),
                leading: const CircleAvatar(
                  backgroundColor: Colors.teal,
                  child: Icon(Icons.key, color: Colors.white),
                ),
                title: const Text(
                  'Passkey di crittografia',
                  style: TextStyle(fontWeight: FontWeight.bold),
                ),
                subtitle: const Text(
                  'Visualizza la passkey di backup dopo aver sbloccato il dispositivo.',
                ),
                trailing: const Icon(Icons.lock_outline, color: Colors.teal),
                onTap: _showEncryptionPasskey,
              ),
            ),
          ],
        ),
      ),
    );
  }

  /// Helper method to build consistent section titles across the page
  Widget _buildSectionTitle(String title) {
    return Padding(
      padding: const EdgeInsets.only(left: 4.0),
      child: Text(
        title,
        style: const TextStyle(
          fontSize: 14,
          fontWeight: FontWeight.bold,
          color: Colors.black54,
          letterSpacing: 0.5,
        ),
      ),
    );
  }
}
